def _segment(seg: str) -> str:
    """조각 하나를 옮긴다. 옮기지 못한 한글은 그대로 남는다."""
    core = seg.strip()
    if not core or not HANGUL.search(core):
        return seg
    lead, trail = seg[:len(seg) - len(seg.lstrip())], seg[len(seg.rstrip()):]
    hit = _lookup(core)
    if hit is not None:
        return lead + hit + trail
    out = core
    for pat, rep in RULES:
        out = pat.sub(rep, out)
    if HANGUL.search(out):
        # 「이름(기준월)」 꼴: 괄호 앞을 사전에서 찾는다.
        m = re.fullmatch(r"(.+?)(\(.*\))", out)
        if m and not HANGUL.search(m.group(2)):
            hit = _lookup(m.group(1))
            if hit is not None:
                out = hit + m.group(2)
    return lead + out + trail


def _lookup(s: str):
    if s in DICT:
        return DICT[s]
    if s.endswith(":") and s[:-1] in DICT:
        return DICT[s[:-1]] + ":"
    return None


def fixed(ko: str):
    """모델 없이 옮길 수 있으면 일본어, 아니면 None(전부 아니면 전무)."""
    if not HANGUL.search(ko):
        return None
    parts = PH.split(ko)
    out = [p if PH.fullmatch(p) else _segment(p) for p in parts]
    ja = "".join(out)
    return None if HANGUL.search(ja) else ja


