def candidates(repo_root=".", recent=20, min_docs=3, max_len=30):
    """경로마다 최근 `recent` 편에서 `min_docs` 편 이상 되풀이되는 한글 조각 (편수, 조각)."""
    import collections
    import subprocess
    from pathlib import Path

    from . import extract

    dirs = ("posts", "news", "weekly", "japan/daily", "japan/posts")
    out = subprocess.run(["git", "ls-files", *dirs], cwd=repo_root, capture_output=True,
                         text=True, check=True).stdout.split()
    groups = collections.defaultdict(list)
    for p in out:
        if p.endswith(".html"):
            groups[p.rsplit("/", 1)[0]].append(p)
    docs = collections.defaultdict(set)
    for ps in groups.values():
        for p in sorted(ps)[-recent:]:
            html = (Path(repo_root) / p).read_bytes().decode("utf-8")
            for u in extract.split(html).units:
                for seg in PH.split(u.ko):
                    seg = seg.strip()
                    if seg and not PH.fullmatch(seg) and HANGUL.search(seg) and len(seg) <= max_len:
                        docs[seg].add(p)
    return sorted(((len(v), k) for k, v in docs.items() if len(v) >= min_docs), key=lambda x: (-x[0], x[1]))


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "--candidates" not in argv:
        print("usage: python3 -m scripts.ja.glossary --candidates", file=sys.stderr)
        return 2
    for n, seg in candidates():
        mark = "=" if fixed(seg) is not None else " "
        print(f"{n:3d} {mark} {seg}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
